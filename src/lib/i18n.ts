export const LOCALES = ["en", "es", "de", "ru", "sr", "mn"] as const;
export type Locale = (typeof LOCALES)[number];

export const LOCALE_META: Record<
  Locale,
  { code: string; native: string; bcp47: string }
> = {
  en: { code: "EN", native: "English", bcp47: "en-GB" },
  es: { code: "ES", native: "Español", bcp47: "es" },
  de: { code: "DE", native: "Deutsch", bcp47: "de" },
  ru: { code: "RU", native: "Русский", bcp47: "ru" },
  sr: { code: "SR", native: "Srpski", bcp47: "sr-Latn" },
  mn: { code: "MN", native: "Монгол", bcp47: "mn" },
};

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const raw = (navigator.languages?.[0] || navigator.language || "en").toLowerCase();
  if (raw.startsWith("es")) return "es";
  if (raw.startsWith("de")) return "de";
  if (raw.startsWith("ru")) return "ru";
  if (raw.startsWith("sr") || raw.startsWith("bs") || raw.startsWith("hr")) return "sr";
  if (raw.startsWith("mn")) return "mn";
  return "en";
}

